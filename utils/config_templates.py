"""
config_templates.py — Generate ORFS config.mk / SDC stubs programmatically.

The repo already ships hand-written, reviewed configs in asic_flow/configs/ —
those are the source of truth. This helper exists for two cases:
  1) bootstrapping a NEW block not yet covered by the shipped configs, and
  2) building SRAM-macro LEF/LIB path lists from an ASAP7 SRAM directory.

It deliberately mirrors the structure/comments of the shipped configs and keeps
the same honesty discipline (all numbers labelled design-intent targets).
"""

from __future__ import annotations

import os
from dataclasses import dataclass, field
from typing import List, Optional


@dataclass
class BlockSpec:
    nickname: str
    design_name: str          # the real top module name
    verilog_files: List[str]  # paths (may use $(RTL)/...)
    clock_port: str = "clk"
    clock_period_ns: float = 1.25      # DESIGN-INTENT TARGET
    core_utilization: int = 55
    place_density: float = 0.60
    core_margin: int = 2
    platform: str = "asap7"
    include_dirs: List[str] = field(default_factory=list)
    extra: List[str] = field(default_factory=list)  # raw extra make lines


def render_config_mk(spec: BlockSpec) -> str:
    files = " \\\n    ".join(spec.verilog_files)
    inc = ""
    if spec.include_dirs:
        inc = "export VERILOG_INCLUDE_DIRS += " + " ".join(spec.include_dirs) + "\n"
    extra = ("\n".join(spec.extra) + "\n") if spec.extra else ""
    return f"""# =============================================================================
# {spec.nickname}.mk — ORFS config (generated by config_templates.py)
# >>> HONESTY NOTE <<< clock/util below are DESIGN-INTENT TARGETS, not results.
# =============================================================================
export DESIGN_NICKNAME = {spec.nickname}
export DESIGN_NAME      = {spec.design_name}
export PLATFORM         = {spec.platform}

JANUS_RTL_ROOT ?= $(realpath $(dir $(DESIGN_CONFIG))/../../../../../..)
RTL := $(JANUS_RTL_ROOT)/rtl

export VERILOG_FILES = \\
    {files}

{inc}export SDC_FILE = $(dir $(DESIGN_CONFIG))/constraint.sdc

export CORE_UTILIZATION   = {spec.core_utilization}
export PLACE_DENSITY      = {spec.place_density}
export CORE_ASPECT_RATIO  = 1.0
export CORE_MARGIN         = {spec.core_margin}
export SYNTH_HIERARCHICAL = 1
{extra}"""


def render_sdc(spec: BlockSpec) -> str:
    return f"""#==============================================================================
# {spec.nickname}.sdc — {spec.design_name} (TARGET constraints, generated)
#==============================================================================
# >>> HONESTY NOTE <<< period is a DESIGN-INTENT TARGET, not closed timing.
create_clock -name core_clk -period {spec.clock_period_ns} [get_ports {spec.clock_port}]
set_clock_uncertainty -setup 0.060 [all_clocks]
set_clock_uncertainty -hold  0.020 [all_clocks]
set_clock_transition  0.050 [all_clocks]
set io_dly [expr 0.30 * {spec.clock_period_ns}]
set_input_delay  -clock core_clk $io_dly [remove_from_collection [all_inputs] [get_ports {spec.clock_port}]]
set_output_delay -clock core_clk $io_dly [all_outputs]
set_load 0.005 [all_outputs]
"""


def sram_macro_lines(asap7_sram_dir: Optional[str]) -> str:
    """Return make lines that add ASAP7 SRAM LEF/LIB if the dir exists."""
    if not asap7_sram_dir or not os.path.isdir(asap7_sram_dir):
        return "# (no ASAP7_SRAM_DIR — caches synthesize from behavioral RTL)\n"
    return (
        "ifneq ($(ASAP7_SRAM_DIR),)\n"
        "  export ADDITIONAL_LEFS += $(wildcard $(ASAP7_SRAM_DIR)/*.lef)\n"
        "  export ADDITIONAL_LIBS += $(wildcard $(ASAP7_SRAM_DIR)/*.lib)\n"
        "endif\n"
    )


def write_block(out_dir: str, spec: BlockSpec, asap7_sram_dir: Optional[str] = None) -> dict:
    os.makedirs(out_dir, exist_ok=True)
    cfg = os.path.join(out_dir, "config.mk")
    sdc = os.path.join(out_dir, "constraint.sdc")
    body = render_config_mk(spec)
    if asap7_sram_dir:
        body += "\n" + sram_macro_lines(asap7_sram_dir)
    with open(cfg, "w") as fh:
        fh.write(body)
    with open(sdc, "w") as fh:
        fh.write(render_sdc(spec))
    return {"config_mk": cfg, "constraint_sdc": sdc}


# ---- self-test --------------------------------------------------------------
if __name__ == "__main__":
    import tempfile
    spec = BlockSpec(
        nickname="demo", design_name="demo_top",
        verilog_files=["$(RTL)/pkg/janus_pkg.sv", "$(RTL)/demo/demo_top.sv"],
        clock_port="clk", clock_period_ns=1.5, core_utilization=50,
    )
    out = write_block(tempfile.mkdtemp(), spec)
    txt = open(out["config_mk"]).read()
    assert "demo_top" in txt and "CORE_UTILIZATION   = 50" in txt
    assert "1.5" in open(out["constraint_sdc"]).read()
    print("config_templates self-test OK:", out)
